def translate(text, language):
    if language != 'ru' or not isinstance(text, str) or not text:
        return text
    if text in RU:
        return RU[text]
    # Account addresses must never be changed by phrase translation.
    emails = []
    def protect(match):
        emails.append(match.group())
        return f'\x00{len(emails) - 1}\x00'
    text = re.sub(r'[\w.+-]+@[\w.-]+\.[A-Za-z]{2,}', protect, text)
    pattern = '|'.join(re.escape(term) for term in sorted(PHRASES, key=len, reverse=True))
    text = re.sub(pattern, lambda match: PHRASES[match.group()], text)
    return re.sub(r'\x00(\d+)\x00', lambda match: emails[int(match.group(1))], text)
